const SLASH_BASS = /\/([A-G](?:#|b)?)$/;
const WORD = /[\p{L}\p{N}]+/gu;

function nearestWordOffset(line, timeMs) {
  if (!line?.text?.trim()) return null;
  if (line.tokens?.length) {
    const token = [...line.tokens].sort((a, b) => {
      const centerA = (a.startMs + a.endMs) / 2;
      const centerB = (b.startMs + b.endMs) / 2;
      return Math.abs(centerA - timeMs) - Math.abs(centerB - timeMs);
    })[0];
    return token?.charStart ?? null;
  }
  const words = [...line.text.matchAll(WORD)];
  if (!words.length) return null;
  const span = Math.max(1, line.endMs - line.startMs);
  const fraction = Math.max(0, Math.min(1, (timeMs - line.startMs) / span));
  const target = Math.round(fraction * Math.max(0, line.text.length - 1));
  return words.reduce((best, word) => Math.abs(word.index - target) < Math.abs(best - target) ? word.index : best, words[0].index);
}

function anchorFor(song, startMs) {
  const line = song.lines?.find((item) => item.startMs <= startMs && startMs < item.endMs);
  const charOffset = nearestWordOffset(line, startMs);
  return line && Number.isInteger(charOffset) ? { lineId: line.id, charOffset } : null;
}

function harmonyRegions(analysis) {
  const regions = analysis?.harmony?.regions;
  if (!Array.isArray(regions)) return [];
  return regions.filter((region) => region?.state === 'harmony' && typeof region.symbol === 'string'
    && region.symbol.trim() && Number.isFinite(region.startMs) && Number.isFinite(region.endMs)
    && region.endMs > region.startMs)
    .map((region) => ({ ...region, startMs: Math.max(0, Math.round(region.startMs)),
      endMs: Math.min(analysis.durationMs || Number.MAX_SAFE_INTEGER, Math.round(region.endMs)) }))
    .filter((region) => region.endMs > region.startMs)
    .sort((a, b) => a.startMs - b.startMs || a.endMs - b.endMs);
}

function subtractIntervals(startMs, endMs, blockers) {
  let spans = [{ startMs, endMs }];
  for (const blocker of blockers) {
    const next = [];
    for (const span of spans) {
      if (blocker.startMs >= span.endMs || blocker.endMs <= span.startMs) next.push(span);
      else {
        if (blocker.startMs > span.startMs) next.push({ startMs: span.startMs, endMs: blocker.startMs });
        if (blocker.endMs < span.endMs) next.push({ startMs: blocker.endMs, endMs: span.endMs });
      }
    }
    spans = next;
  }
  return spans.filter((span) => span.endMs > span.startMs);
}

/**
 * Project a v6 analysis into SongDocument v2 chord events. Since v2 has no
 * per-chord confidence field, estimated provenance is returned separately
 * for the local project and explained in reviewWarnings.
 */
export function projectAnalysisChords(song, analysis, { previousGeneratedIds = [] } = {}) {
  const priorIds = new Set(previousGeneratedIds);
  const retained = (song.chords || []).filter((chord) => !priorIds.has(chord.id));
  const reservedIds = new Set(retained.map((chord) => chord.id));
  const output = [];
  const provenance = [];
  const warnings = [];
  const regions = harmonyRegions(analysis);

  for (const region of regions) {
    const fragments = subtractIntervals(region.startMs, region.endMs, [...retained, ...output]);
    for (const fragment of fragments) {
      const id = `ch-${fragment.startMs}`;
      if (reservedIds.has(id)) {
        warnings.push(`No se añadió el acorde estimado de ${fragment.startMs} ms porque ya existe un evento con el mismo ID.`);
        continue;
      }
      reservedIds.add(id);
      const slashBass = SLASH_BASS.exec(region.symbol)?.[1] || null;
      const chord = { id, startMs: fragment.startMs, endMs: fragment.endMs, symbol: region.symbol,
        bassNote: slashBass, anchor: anchorFor(song, fragment.startMs), scale: null };
      output.push(chord);
      provenance.push({ chordId: id, status: 'estimated', regionId: region.id || null,
        analysisStartMs: region.startMs, analysisEndMs: region.endMs });
    }
  }

  if (output.length) warnings.push(`${output.length} acorde(s) proceden del análisis automático y quedan estimados hasta que los revises.`);
  const chords = [...retained, ...output].sort((a, b) => a.startMs - b.startMs || a.id.localeCompare(b.id));
  return { chords, generatedChordIds: output.map((chord) => chord.id), provenance, warnings };
}

/** Idempotent chart replacement: removes only IDs previously generated by this sync. */
export function syncAnalysisToSong(song, analysis, options = {}) {
  const projected = projectAnalysisChords(song, analysis, options);
  return {
    song: { ...song, chords: projected.chords,
      reviewWarnings: Array.from(new Set([...(song.reviewWarnings || [])
        .filter((warning) => !/^\d+ acorde\(s\) proceden del análisis automático/.test(warning)), ...projected.warnings])) },
    generatedChordIds: projected.generatedChordIds,
    provenance: projected.provenance,
    warnings: projected.warnings,
  };
}
